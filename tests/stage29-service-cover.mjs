/** One changed road: real walk, projectiles, route commit and map-revision retry.
 * Actors/resources/prior goals are explicit fixtures; this is not a chapter clear.
 */
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {runtime,battlefield} from '../game/tests/helpers.mjs';
const plain=x=>JSON.parse(JSON.stringify(x));
import {traverse} from './stage16-temple-traverse-helper.mjs';
import {authorStage29ServiceCover,SERVICE_COVER_ROUTE} from '../tools/map-forge/stage29-service-cover.mjs';

const g=await runtime({legacyMaps:false}),C=g.HONRO_CORE,current=plain(g.HONRO_PROJECT);
const before=plain(current);before.stages[28]=JSON.parse(await readFile('tests/fixtures/stage29-service-cover/before-stage.json','utf8'));
const raw=JSON.parse(await readFile('shared/data/campaign.json','utf8'));
const stage=raw.stages[28],old=before.stages[28],rows=[];
assert.deepEqual(plain(authorStage29ServiceCover(current)),current,'Idempotent targeted authoring');
const rawBefore=plain(raw);rawBefore.stages[28]=old;
const authored=authorStage29ServiceCover(rawBefore);
assert.deepEqual(authored.stages.filter((_,i)=>i!==28),rawBefore.stages.filter((_,i)=>i!==28),'Other29 retained');
assert.deepEqual(authored.library,rawBefore.library,'Shared library retained');
for(const key of ['events','markers','initialState','anchors','environment','width','height'])assert.deepEqual(stage[key],old[key],key+' retained');
assert.deepEqual(stage.terrains.filter(t=>t.id!=='r29-high-road'),old.terrains.filter(t=>t.id!=='r29-high-road'),'Other terrain retained');
assert.deepEqual(stage.units.map(u=>[u.id,u.kind,u.team,u.stageOverrides]),old.units.map(u=>[u.id,u.kind,u.team,u.stageOverrides]),'Identities, party, elites and power overrides retained');
assert.equal(stage.units.filter(u=>u.team==='enemy').length,27);
assert.equal(stage.units.filter(u=>u.team==='enemy'&&u.stageOverrides.honroAct3Elite).length,7);
assert.deepEqual(stage.design.questRoutes,old.design.questRoutes,'Both exit choices retained');

function fixture(project,{from={x:5000,y:1840},target=true}={}){
 g.HONRO_PROJECT=project;
 const q=battlefield(g,29),u=q.e.heroesAlive().find(v=>v.cls==='mage'),v=q.e.unit('a3-29-dark-lock-approach-4');
 q.b.units=target?[u,v]:[u];q.b.active=u.id;q.b.side=0;q.b.phase='aim';q.e.checkEnd=()=>false;
 Object.assign(u,{...from,vx:0,vy:0,airborne:false,jumping:false});
 assert(C.validTerrainContactPose(q.b.terrain,u),'Supported starting pose');
 return{...q,u,v};
}
function fire(q,angle,power){
 const hp=q.v.hp,pred=q.e.predict(q.u,C.SKILLS.M01,angle,power,q.v,false);
 assert(q.e.fire('M01',angle,power),'Actual free basic projectile');
 for(let tick=0;tick<2400&&q.b.projectiles.length;tick++)for(const p of [...q.b.projectiles])if(q.b.projectiles.includes(p))q.e.stepProjectile(p,C.STEP);
 return {from:{x:q.u.x,y:q.u.y},angle,power,damage:hp-q.v.hp,predicted:{unit:pred.unit,terrain:pred.terrain,x:pred.x,y:pred.y}};
}
const lowBefore=fire(fixture(before),0,1),lowAfter=fire(fixture(current),0,1);
assert(lowBefore.damage>0,'Flat former road permits the low shot');
assert.equal(lowAfter.damage,0,'New service rise stops that same live shot');
assert.equal(lowAfter.predicted.terrain,'r29-high-road');
rows.push({kind:'same-basic-shot',before:lowBefore,after:lowAfter});
const high=fixture(current,{from:{x:5230,y:1745}});
const aim=high.e.shotSeeds(high.u,C.SKILLS.M01,high.v).find(a=>high.e.predict(high.u,C.SKILLS.M01,a.angle,a.power,high.v,false).unit===high.v.id);
assert(aim,'Crest provides a real firing angle');const raised=fire(high,aim.angle,aim.power);assert(raised.damage>0);rows.push({kind:'raised-basic-shot',...raised});

const route=fixture(current,{target:false});
const across=traverse(g,route.b,route.e,route.u,SERVICE_COVER_ROUTE,{jump:false});assert(across.passed&&across.damage===0&&across.jumps===0);
const returned=traverse(g,route.b,route.e,route.u,[...SERVICE_COVER_ROUTE].reverse(),{jump:false});assert(returned.passed&&returned.damage===0);
rows.push({kind:'two-way-base-walk',across,returned});
const toExit=traverse(g,route.b,route.e,route.u,[...SERVICE_COVER_ROUTE,{x:5550,y:1840},{x:6100,y:2190},{x:6350,y:2190}],{jump:false});assert(toExit.passed&&toExit.damage===0);
// Explicit earlier-objectives-completed fixture; arrival after this setup is
// generated by the preceding real movement, never an exit-position assignment.
const memory=g.HonroAct3.memory(route.b);memory.done['old-seal']=memory.done['hyeonmuk-letter']=true;
route.b.honroStory=null;route.b.honroState.storyQueue=[];route.b.honroState.deferredStory=[];
assert(g.HonroRouteBranches.commit(route.app,g.HonroAct3.steps(route.b).find(s=>s.kind==='route')));
assert.equal(route.b.honroRouteChoice.selectedRoute,'A');rows.push({kind:'existing-upper-exit-commit',toExit,choice:plain(route.b.honroRouteChoice)});

g.HONRO_PROJECT=current;
const retry=battlefield(g,29),p=plain(retry.p);
assert.equal(retry.b.honroCampaignMapRevision,2);
for(let id=1;id<=28;id++)p.cleared[id]={visits:1,rounds:5};
p.honroGrowth=plain(retry.b.honroGrowth.ledger);
p.honroGrowth.stages[29].limit=plain(retry.b.honroGrowth.limit);
p.honroBattle=plain(retry.b);p.honroBattle.honroCampaignMapRevision=1;
const saved=Object.fromEntries(['heroes','loadouts','cleared','honroGrowth'].map(k=>[k,plain(p[k])]));
assert(g.HonroCampaignMapRevision.discard(p));assert.equal(p.honroBattle,null);assert.equal(p.honroMapRestart,29);
for(const[k,v]of Object.entries(saved))assert.deepEqual(plain(p[k]),v,k+' retained on revision retry');
const restarted=battlefield(g,p.honroMapRestart,{profile:p});assert.equal(restarted.b.honroStage,29);assert.equal(restarted.b.honroCampaignMapRevision,2);
rows.push({kind:'revision1-discard-and-stage29-rebuild',revision:2,preserved:Object.keys(saved)});
const out='_local/reports/act3-terrain-continuation-20261020';await mkdir(out,{recursive:true});
await writeFile(out+'/stage29-service-cover.json',JSON.stringify({scope:'Isolated actual movement and basic projectiles; previous goals explicit fixture; Direct existing revision discard and fresh-world rebuild; no App/storage test. Not normal-resource chapter completion.',rows},null,2)+'\n');
console.log('PASS Stage29 service cover: live shot blocked/raised shot hits, two-way walking, upper exit commit and revision retry');
