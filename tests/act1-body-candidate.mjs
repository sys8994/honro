import assert from 'node:assert/strict';
import vm from 'node:vm';
import {runtimeParts} from '../shared/build.mjs';
import {applyAct1BodyCandidate} from '../tools/act1-vector-production/apply-body-candidate.mjs';
const plain=v=>JSON.parse(JSON.stringify(v));
delete process.env.HONRO_ACT1_BODY_CANDIDATE;
const g=vm.createContext({console,performance,structuredClone,setTimeout,clearTimeout});g.window=g;
for(const part of await runtimeParts({vector:false,render:false,productionStory:true}))vm.runInContext(part,g);
const original=plain(g.HONRO_PROJECT),snapshot=JSON.stringify(original),before=original.stages.find(s=>s.metadata?.stageId===1);
assert.equal(await applyAct1BodyCandidate(original),original,'default must remain unchanged');
process.env.HONRO_ACT1_BODY_CANDIDATE='1';
const next=await applyAct1BodyCandidate(original),after=next.stages.find(s=>s.metadata?.stageId===1);
assert.equal(JSON.stringify(original),snapshot,'candidate authoring mutates source');
for(const k of Object.keys(before).filter(k=>k!=='elements'))assert.deepEqual(after[k],before[k],`changed ${k}`);
assert.deepEqual(after.elements.slice(0,-1),before.elements);
assert.deepEqual(next.stages.filter(s=>s.metadata?.stageId!==1),original.stages.filter(s=>s.metadata?.stageId!==1));
const asset=next.library.at(-1);assert.deepEqual(Array.from(g.HonroVectorArt.validate(asset.vector)),[]);assert.deepEqual(asset.collision,[]);
const oldMap=g.HonroMaps.compile(before,original),newMap=g.HonroMaps.compile(after,next);
assert.deepEqual(plain(newMap.terrain),plain(oldMap.terrain));assert.deepEqual(plain(newMap.worldTerrain),plain(oldMap.worldTerrain));
assert.equal(newMap.landmarks.length,oldMap.landmarks.length+1);assert.equal(newMap.elements.at(-1).collisionIds.length,0);
const broken=plain(original);broken.stages.find(s=>s.metadata?.stageId===1).terrains[0].points[0].y+=1;
assert.throws(()=>applyAct1BodyCandidate(broken),/geometry changed/);
assert.throws(()=>applyAct1BodyCandidate(next),/Duplicate/);
delete process.env.HONRO_ACT1_BODY_CANDIDATE;
console.log(JSON.stringify({stage:1,defaultUnchanged:true,geometryLocked:true,collisionUnchanged:true,worldTerrainUnchanged:true,otherStagesUnchanged:true,nativeFormat:true,browserAccepted:false,gameplayAccepted:false}));
