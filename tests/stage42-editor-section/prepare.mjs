import fs from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {installEditor} from './patch.mjs';
const root=process.argv[2];
if(!root)throw Error('usage: node prepare.mjs <separate disposable fixture root>');
const manifest=JSON.parse(fs.readFileSync(path.resolve(root,'web/manifest.json'),'utf8'));
if(!/^web\/entries\/workshop\.[a-f0-9]+\.js$/.test(manifest.workshopEntry))throw Error('unknown active Workshop entry');
if(!fs.readFileSync(path.resolve(root,'HONRO_WORKSHOP.html'),'utf8').includes('src="'+manifest.workshopEntry+'"'))throw Error('Active Workshop HTML/runtime manifest mismatch');
const entry=fs.readFileSync(path.resolve(root,manifest.workshopEntry),'utf8');
const active=[...new Set(entry.match(/workshop-app\.[a-f0-9]+\.js/g)??[])];
if(active.length!==1||active[0]!=='workshop-app.489f733634454986.js')throw Error('Active workshop runtime not pinned');
const f=path.resolve(root,'web/runtime',active[0]);
const original=fs.readFileSync(f);
if(createHash('sha256').update(original).digest('hex')!=='489f733634454986a5f4cd94468e7b7393a18508ee1e02e1ce0cad77ab8b324f')throw Error('unexpected official fixture; refusing to patch');
fs.writeFileSync(f,installEditor(original.toString('utf8')));
