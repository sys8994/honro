import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
const [stock,test,out]=process.argv.slice(2);
const read=(r,p)=>fs.readFileSync(path.join(r,p)),json=(r,p)=>JSON.parse(read(r,p));
const sha=x=>createHash('sha256').update(x).digest('hex');
const a=json(stock,'web/manifest.json'),b=json(test,'web/manifest.json');
assert.equal(a.project,b.project);
assert(read(stock,a.project).equals(read(test,b.project)));
assert.notEqual(a.gameEntry,b.gameEntry,'Expected distinct compiled runtime entries');
const c=json(stock,a.project), id='approved34:coastal-foundation';
assert.equal(c.libraryOrder.filter(s=>s===id).length,1);
const p=c.stageLibraries[33],s=c.stages[33],compat=c.compatibility34;
assert.equal(p,'web/data/chapter-34-assets.3828bd02ec5b054c.json');
assert.equal(c.assetEncodings.stageLibraries[33],'json');
for(const f of [p,s,compat].filter(Boolean))assert(read(stock,f).equals(read(test,f)),f);
const assets=json(stock,p);assert.equal(assets.filter(x=>x.id===id).length,1);
const x=assets.find(m=>m.id===id), h=sha(JSON.stringify(x));
assert.equal(h,'2fef77efb6c2d03544e68260cec7405f30d6af011c1f8f61cb64bf8219a5a2b6');
const stage=json(stock,s);
assert.equal(stage.metadata?.stageId,34);assert.equal(stage.terrains.length,17);
assert.deepEqual(Object.keys(x.vector.clips),['source-alpha-silhouette']);
const receipts={id,oldAssetSha:h,keys:[],runtimeEntry:{stock:a.gameEntry,trial:b.gameEntry},stageSha:sha(JSON.stringify(stage)),verifiedExactAssetPacket:p,verifiedExactSceneInputs:[p,s,compat,a.project].filter(Boolean),verifiedActualAssets:assets.map(x=>({id:x.id,hash:sha(JSON.stringify(x))}))};
fs.writeFileSync(path.join(out,'asset-contract.json'),JSON.stringify(receipts,null,2));
