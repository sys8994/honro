for name in sys.argv[1:] or configs:
    ox,oy,parts=configs[name]
    a=np.array(Image.open(Path('cutouts')/(name+'.png')).convert('RGBA'));h,w=a.shape[:2]
    source=a[:,:,3]>0
    out=Path('rig-parts')/name;out.mkdir(parents=True,exist_ok=True)
    masks=[]
    for p in parts:
        im=Image.new('L',(w,h));ImageDraw.Draw(im).polygon(p.pop('polygon'),fill=255)
        masks.append((np.asarray(im)>0)&source)
    missing=source&~np.logical_or.reduce(masks)
    closest=np.argmin([distance_transform_edt(~mask) for mask in masks],axis=0)
    for i,(p,mask) in enumerate(zip(parts,masks)):
        mask |= missing & (closest==i)
        z=a.copy(); z[:,:,3]=mask.astype(np.uint8)*255
        Image.fromarray(z).save(out/(p['id']+'.png'))
    assert np.array_equal(np.logical_or.reduce(masks),source)
    (out/'parts.json').write_text(json.dumps({'origin':[ox,oy],'size':[w,h],'parts':parts},indent=2)+'\n')
    print(name,'semantic coverage',f'{1-missing.sum()/source.sum():.2%}')
