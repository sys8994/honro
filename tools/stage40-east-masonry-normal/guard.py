"""One detached ordinary df621 Stage42/C2 build, no publication, source/graph custody only."""
from pathlib import Path
import hashlib,json,os,re,stat,subprocess,sys,zipfile
D=Path(__file__).resolve().parent;P=json.loads((D/'PINS.json').read_bytes())
R=Path(os.environ.get('GITHUB_WORKSPACE',Path.cwd())).resolve();B=P['base']['head'];M='web/manifest.json'
WF='.github/workflows/stage40-east-masonry-c2-canonical-df621-r2.yml'
TOOL='tools/stage40-east-masonry-normal/'
SHELLS={'HONRO.html','index.html','HONRO_WORKSHOP.html'}
KEEP={'previousFiles','previousGenerations','publishedGenerations','publishedRetention'}
def need(x,m):
    if not x:raise RuntimeError(m)
def sha(b):return hashlib.sha256(b).hexdigest()
def blob(b):return hashlib.sha1(b'blob '+str(len(b)).encode()+b'\x00'+b).hexdigest()
def fact(b):return {'bytes':len(b),'sha256':sha(b)}
def git(q,*args):return subprocess.check_output(['git','-C',str(q),*args],text=True,timeout=150).strip()
def dump(p,v):p.write_text(json.dumps(v,indent=2)+'\n')
def read(p,k):
    q=p/k;need(q.resolve()==q and q.is_file() and stat.S_ISREG(q.lstat().st_mode),'bad exact path '+k)
    return q.read_bytes()
def idx(m):
    r={x['path']:{k:x[k]for k in ('bytes','sha256')}for x in m['files']}
    need(len(r)==len(m['files']) and all(re.fullmatch(r'web/(runtime|entries|data|styles|graphics|fonts)/[\w.-]+',k,re.ASCII)for k in r),'invalid graph path')
    return r
def enabled():
    need(P['enabled'] is True and os.getenv('GITHUB_REPOSITORY')=='sys8994/honro' and os.getenv('GITHUB_REF')=='refs/heads/'+P['branch'] and sha(read(D,'observer.json'))==P['observerSha256'],'disabled: exact scoped ref only')
def pre(w):
    need(git(R,'rev-parse','HEAD')==os.environ['GITHUB_SHA'] and git(R,'show','-s','--format=%P','HEAD')==B and git(R,'rev-parse',B+'^{tree}')==P['base']['tree'] and not git(R,'status','--porcelain'),'wrong sole parent QA checkout')
    names={WF,*(TOOL+x for x in ['PINS.json','observer.json','guard.py','native.py'])}
    expect={'A\t'+k for k in names}|{('M' if v['before'] else 'A')+'\t'+k for k,v in P['source'].items()}
    need(set(git(R,'diff','--name-status','--no-renames',B,'HEAD').splitlines())==expect,'wrong exact review diff')
    for k,v in P['source'].items():
        need(blob(read(R,k))==v['after'] and git(R,'ls-tree','HEAD','--',k).startswith('100644 '),'wrong reviewed two files')
        if v['before']:need(git(R,'rev-parse',B+':'+k)==v['before'],'unexpected baseline source')
    def api(route):return json.loads(subprocess.check_output(['gh','api','repos/sys8994/honro/actions/'+route],timeout=75))
    for a in (P['pages'],P['old']):
        r,j=api(f"runs/{a['run']}"),api(f"jobs/{a['job']}")
        need((r['head_sha'],r['head_branch'],r['name'],r['conclusion'])==(a['head'],'master','pages build and deployment','success') and (j['head_sha'],j['run_id'],j['name'],j['conclusion'])==(a['head'],a['run'],'deploy','success') and any(v['name']=='Deploy to GitHub Pages' and v['conclusion']=='success' for v in j['steps']),'incorrect attested historical Pages')
    for n in ('B','C'):git(R,'-c','core.hooksPath=/dev/null','worktree','add','--detach',str(w/n),B)
    subprocess.run(['git','init','-q',str(w/'H')],check=True,timeout=35)
    h=w/'H';git(h,'-c','credential.helper=','-c','http.extraHeader=','fetch','--no-tags','--depth=1','https://github.com/sys8994/honro.git',P['old']['head']);git(h,'-c','core.hooksPath=/dev/null','checkout','--detach','FETCH_HEAD')
    need(git(h,'rev-parse','HEAD')==P['old']['head'] and git(h,'rev-parse','HEAD^{tree}')==P['old']['tree'] and not git(h,'status','--porcelain'),'wrong oldest real app')
    for k,v in {'HONRO.html':P['oldProof']['shell'],M:P['oldProof']['manifest'],**P['oldProof']['files']}.items():need(fact(read(h,k))==v,'old route differs '+k)
    stock,cn=w/'B',w/'C'
    need(all(not git(q,'status','--porcelain') and git(q,'rev-parse','HEAD^{tree}')==P['base']['tree'] for q in [stock,cn]),'dirty build fixture')
    bm=read(stock,M);need({**fact(bm),'git':blob(bm)}==P['base']['manifest'],'published df621 manifest changed')
    need(all(not (q/P['generatedWorld']['path']).exists() and not (q/P['generatedWorld']['path']).is_symlink() for q in (stock,cn)),'world.json should be generated by normal build, not tracked or supplied')
    for v in P['stockGraph'].values():
        raw=read(stock,v['path']);need({**fact(raw),'git':blob(raw)}=={k:x for k,x in v.items() if k!='path'},'wrong signed live A '+v['path'])
    for k,v in P['sourceAuthority'].items():need(blob(read(stock,k))==blob(read(cn,k))==v,'built authority changed '+k)
    for k,v in P['source'].items():(cn/k).write_bytes(read(R,k))
    for k in ('package.json','package-lock.json','game/package.json','game/package-lock.json'):
        l=read(cn,k);need(l==read(stock,k),'locked npm source changed')
        if k.endswith('lock.json'):
            a=json.loads(l);need(a['lockfileVersion']==3 and all(not x or x.startswith('node_modules/') and not y.get('link') and re.fullmatch(r'https://registry\.npmjs\.org/[^?#]+\.tgz',y.get('resolved','')) and re.fullmatch(r'sha512-[A-Za-z0-9+/]+={0,2}',y.get('integrity','')) for x,y in a['packages'].items()),'untrusted dependency')
    dump(w/'out'/'SOURCE.json',{'status':'EXACT_REVIEWED_DF621_SOURCE_LOCAL_ONLY','head':B,'tree':P['base']['tree'],'source':P['source'],'historicalSaveAuthor':P['old']['head'],'sourceVisualProof':P['sourceVisualProof']})
def generated(w):
    v=P['generatedWorld'];raw=read(w/'C',v['path']);need(fact(raw)=={k:x for k,x in v.items() if k!='path'},'ordinary build did not materialize exact canonical world.json')
    dump(w/'out'/'GENERATED-WORLD.json',{'status':'NATURAL_BUILD_OUTPUT_EXACT_BEFORE_CONTRACT',**v})
def graph(w):
    a,b=w/'B',w/'C';am,bm=[json.loads(read(x,M))for x in [a,b]];aa,ba=map(idx,[am,bm])
    for q,rows in [(a,aa),(b,ba)]:
        for k,v in rows.items():need(fact(read(q,k))==v,'physical active mismatch '+k)
    ac,bc=[json.loads(read(q,m['project']))for q,m in [(a,am),(b,bm)]]
    ap=P['stage40']['packet'];cp=P['newPacket']['path']
    need(ac['stageLibraries'][39]==ap and bc['stageLibraries'][39]==cp and bc['assetEncodings']['stageLibraries'][39]=='json','stage40 active not intended canonical C2 packet')
    c0,c1=json.loads(read(a,ap)),json.loads(read(b,cp));need(fact(read(b,cp))=={k:v for k,v in P['newPacket'].items() if k!='path'} and blob(read(a,ap))==P['stage40']['packetGit'],'wrong exact direct packet')
    need(len(c0)==len(c1)==15 and [e['id'] for e in c0]==[e['id'] for e in c1],'provider ordering drift')
    nb=next(x for x in c1 if x['id']=='approved40:body');need(sha(json.dumps(nb,ensure_ascii=False,separators=(',',':')).encode())=='66fd057b03754601c0be187fda50a8042f13863a754bafecab77b13d70985440','exact rebuilt C2 provider drift')
    del nb['vector']['root']['children'][0]['children'][24:];need(c0==c1,'changed any other provider/metadata')
    exact=json.loads(read(b,bm['project']));exact['stageLibraries'][39]=ap;need(ac==exact,'unrelated stage/campaign closure changed')
    need(len(ac['stages'])==len(ac['stageLibraries'])==50 and all(aa[k]==ba[k]for k in ac['stages']+[k for k in ac['stageLibraries'] if k!=ap]),'protected 50 maps or 49 providers differ')
    s42=P['protectedStage42'];need(ac['stages'][41]==bc['stages'][41]==s42['map'] and ac['stageLibraries'][41]==bc['stageLibraries'][41]==s42['provider'] and aa[s42['provider']]==ba[s42['provider']] and aa[s42['provider']]['sha256']==s42['providerSHA256'] and s42['common5'] in am['common'] and s42['common5'] in bm['common'] and aa[s42['common5']]==ba[s42['common5']],'published Stage42 provider/physical map/save runtime lost')
    need(len(aa)==len(ba)==P['base']['activeFiles'],'normal active graph count differs from exact latest parent')
    def pick(m,prefix):
        f=[x for x in m['common'] if x.startswith(prefix)];need(len(f)==1,'unexpected graph role '+prefix);return f[0]
    def embed(m):
        z=m['playtest'];need(z.endswith('?embedded=1'),'wrong Playtest route');return z.removesuffix('?embedded=1')
    roles=[(ap,cp),(am['project'],bm['project']),(pick(am,'web/runtime/campaign.'),pick(bm,'web/runtime/campaign.')),(P['stage40']['common12'],pick(bm,'web/runtime/ordered-common-12.')),(am['gameEntry'],bm['gameEntry']),(am['workshopEntry'],bm['workshopEntry']),(embed(am),embed(bm))]
    pairs=dict(roles);need(len(pairs)==7 and all(x!=y for x,y in roles) and aa.keys()-ba.keys()==pairs.keys() and ba.keys()-aa.keys()==set(pairs.values()) and all(aa[k]==ba[k]for k in aa.keys()&ba.keys()),'extra active graph difference')
    def norm(s):
        for x,y in roles:s=s.replace(x,y).replace(Path(x).name,Path(y).name)
        return s
    def convert(o):
        if isinstance(o,str):return norm(o)
        if isinstance(o,list):return [convert(x)for x in o]
        if isinstance(o,dict):return {k:convert(v)for k,v in o.items()}
        return o
    need(convert({k:v for k,v in am.items()if k not in KEEP|{'files'}})=={k:v for k,v in bm.items()if k not in KEEP|{'files'}},'other bootstrap or manifest changed')
    ck=P['stage40']['common12'];need(blob(read(a,ck))==P['stage40']['common12Git'],'wrong prior Stage40 registry chunk')
    row='"approved40:body":{stage:40,previous:"4724416:12a0c1d5",previousOptimized:["4471109:d3f5a835"],current:"1644042:df21ebc3"}'
    new=row.replace('["4471109:d3f5a835"]','["4471109:d3f5a835","1644042:df21ebc3"]').replace('current:"1644042:df21ebc3"','current:"1647277:af3b90a3"')
    js=read(a,ck).decode();need(js.count(row)==1 and js.replace(row,new).encode()==read(b,pairs[ck]),'compiled registry changed beyond exact body row')
    for x,y in roles[2:3]+roles[4:]:
        if x==am['workshopEntry']:
            marker='globalThis.HONRO_PLAYTEST_URL='+json.dumps(am['playtest'])
            need(read(a,x).decode().count(marker)==1,'Workshop embedded literal missing')
        need(norm(read(a,x).decode()).encode()==read(b,y),'bootstrap changed beyond signed aliases '+x)
    for s in SHELLS:need(norm(read(a,s).decode()).encode()==read(b,s),'visible shell changed beyond signed aliases '+s)
    for k,v in P['source'].items():need(blob(read(b,k))==v['after'],'normal build damaged signed source '+k)
    for k,v in P['sourceAuthority'].items():need(blob(read(b,k))==v,'normal build mutated latest protected authority '+k)
    gs=set(pairs.values())|SHELLS|{M};out=w/'out'
    bundle=out/'C2-COMPILED-QA-ONLY.zip'
    with zipfile.ZipFile(bundle,'w',compression=zipfile.ZIP_DEFLATED) as z:
        for k in sorted(gs):z.write(b/k,k)
    with zipfile.ZipFile(bundle) as z:need(z.testzip() is None and set(z.namelist())==gs,'QA overlay zip changed')
    dump(out/'NORMAL-GRAPH.json',{'status':'PASS_EXACT_C2_CANONICAL_NO_DEPLOY','base':B,'scope':'50 maps and 49 providers exact; existing external chapters unmodified','aliases':pairs,'activeFiles':len(ba),'stage42Preserved':s42,'packet':P['newPacket'],'normalQaZip':fact(bundle.read_bytes()),'generated':{k:{**fact(read(b,k)),'git':blob(read(b,k))}for k in sorted(gs)}})
