def need(x,m):
    if not x:raise RuntimeError(m)
def sha(b):return hashlib.sha256(b).hexdigest()
def blob(b):return hashlib.sha1(b'blob '+str(len(b)).encode()+b'\x00'+b).hexdigest()
def fact(b):return {'bytes':len(b),'sha256':sha(b)}
def git(q,*args):return subprocess.check_output(['git','-C',str(q),*args],text=True,timeout=150).strip()
def dump(p,v):p.write_text(json.dumps(v,indent=2)+'\n')
def read(p,k):
    q=p/k;need(q.resolve()==q and q.is_file() and stat.S_ISREG(q.lstat().st_mode),'bad exact path '+k)
    return q.read_bytes()
def idx(m):
    r={x['path']:{k:x[k]for k in ('bytes','sha256')}for x in m['files']}
    need(len(r)==len(m['files']) and all(re.fullmatch(r'web/(runtime|entries|data|styles|graphics|fonts)/[\w.-]+',k,re.ASCII)for k in r),'invalid graph path')
    return r
def enabled():
    need(P['enabled'] is True and os.getenv('GITHUB_REPOSITORY')=='sys8994/honro' and os.getenv('GITHUB_REF')=='refs/heads/'+P['branch'] and sha(read(D,'observer.json'))==P['observerSha256'],'disabled: exact scoped ref only')
def pre(w):
    need(git(R,'rev-parse','HEAD')==os.environ['GITHUB_SHA'] and git(R,'show','-s','--format=%P','HEAD')==B and git(R,'rev-parse',B+'^{tree}')==P['base']['tree'] and not git(R,'status','--porcelain'),'wrong sole parent QA checkout')
    names={WF,*(TOOL+x for x in ['PINS.json','observer.json','guard.py','native.py'])}
    expect={'A\t'+k for k in names}|{('M' if v['before'] else 'A')+'\t'+k for k,v in P['source'].items()}
    need(set(git(R,'diff','--name-status','--no-renames',B,'HEAD').splitlines())==expect,'wrong exact review diff')
    for k,v in P['source'].items():
        need(blob(read(R,k))==v['after'] and git(R,'ls-tree','HEAD','--',k).startswith('100644 '),'wrong reviewed single recovery source')
        if v['before']:need(git(R,'rev-parse',B+':'+k)==v['before'],'unexpected baseline source')
    def api(route):return json.loads(subprocess.check_output(['gh','api','repos/sys8994/honro/actions/'+route],timeout=75))
    for a in (P['pages'],P['old']):
        r,j=api(f"runs/{a['run']}"),api(f"jobs/{a['job']}")
        need((r['head_sha'],r['head_branch'],r['name'],r['conclusion'])==(a['head'],'master','pages build and deployment','success') and (j['head_sha'],j['run_id'],j['name'],j['conclusion'])==(a['head'],a['run'],'deploy','success') and any(v['name']=='Deploy to GitHub Pages' and v['conclusion']=='success' for v in j['steps']),'incorrect attested historical Pages')
    for n in ('B','F','C'):git(R,'-c','core.hooksPath=/dev/null','worktree','add','--detach',str(w/n),B)
    subprocess.run(['git','init','-q',str(w/'H')],check=True,timeout=35)
    h=w/'H';git(h,'-c','credential.helper=','-c','http.extraHeader=','fetch','--no-tags','--depth=1','https://github.com/sys8994/honro.git',P['old']['head']);git(h,'-c','core.hooksPath=/dev/null','checkout','--detach','FETCH_HEAD')
    need(git(h,'rev-parse','HEAD')==P['old']['head'] and git(h,'rev-parse','HEAD^{tree}')==P['old']['tree'] and not git(h,'status','--porcelain'),'wrong oldest real app')
    for k,v in {'HONRO.html':P['oldProof']['shell'],M:P['oldProof']['manifest'],**P['oldProof']['files']}.items():need(fact(read(h,k))==v,'old route differs '+k)
    stock,cn=w/'B',w/'F'
    need(all(not git(q,'status','--porcelain') and git(q,'rev-parse','HEAD^{tree}')==P['base']['tree'] for q in [stock,cn]),'dirty build fixture')
    bm=read(stock,M);need({**fact(bm),'git':blob(bm)}==P['base']['manifest'],'published df621 manifest changed')
    need(all(not (q/P['generatedWorld']['path']).exists() and not (q/P['generatedWorld']['path']).is_symlink() for q in (stock,cn)),'world.json should be generated by normal build, not tracked or supplied')
    for v in P['stockGraph'].values():
        raw=read(stock,v['path']);need({**fact(raw),'git':blob(raw)}=={k:x for k,x in v.items() if k!='path'},'wrong signed live A '+v['path'])
    for k,v in P['sourceAuthority'].items():need(blob(read(stock,k))==blob(read(cn,k))==v,'built authority changed '+k)
    reconstruct_c2(w,api)
    for k,v in P['source'].items():(cn/k).write_bytes(read(R,k))
    for k in ('package.json','package-lock.json','game/package.json','game/package-lock.json'):
        l=read(cn,k);need(l==read(stock,k),'locked npm source changed')
        if k.endswith('lock.json'):
            a=json.loads(l);need(a['lockfileVersion']==3 and all(not x or x.startswith('node_modules/') and not y.get('link') and re.fullmatch(r'https://registry\.npmjs\.org/[^?#]+\.tgz',y.get('resolved','')) and re.fullmatch(r'sha512-[A-Za-z0-9+/]+={0,2}',y.get('integrity','')) for x,y in a['packages'].items()),'untrusted dependency')
    dump(w/'out'/'SOURCE.json',{'status':'EXACT_REVIEWED_DF621_SOURCE_LOCAL_ONLY','head':B,'tree':P['base']['tree'],'source':P['source'],'historicalSaveAuthor':P['old']['head'],'c2Official':P['c2Official']})
def generated(w):
    v=P['generatedWorld'];raw=read(w/'F',v['path']);need(fact(raw)=={k:x for k,x in v.items() if k!='path'},'ordinary build did not materialize exact canonical world.json')
    dump(w/'out'/'GENERATED-WORLD.json',{'status':'NATURAL_BUILD_OUTPUT_EXACT_BEFORE_CONTRACT',**v})
def reconstruct_c2(w,api):
    a=P['c2Official'];run,job,art=[api(route) for route in (f"runs/{a['run']}",f"jobs/{a['job']}",f"artifacts/{a['artifact']}")]
    need((run['head_sha'],run['head_branch'],run['conclusion'])==(a['head'],a['branch'],'success') and (job['head_sha'],job['run_id'],job['name'],job['conclusion'])==(a['head'],a['run'],'canonical','success'),'prior C2 official run/job mismatch')
    need(art['id']==a['artifact'] and art['name']==a['name'] and art['expired'] is False and art['workflow_run']['id']==a['run'] and art['workflow_run']['head_sha']==a['head'] and art['digest']=='sha256:'+a['outer']['sha256'] and art['size_in_bytes']==a['outer']['bytes'],'prior C2 artifact API mismatch')
    raw=subprocess.check_output(['gh','api','--allow-escape-sequences',f"repos/sys8994/honro/actions/artifacts/{a['artifact']}/zip"],timeout=100)
    restore_compiled(w,raw)
def restore_compiled(w,raw):
    import io
    a=P['c2Official'];need(fact(raw)==a['outer'],'prior C2 outer bytes differ')
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        need(z.testzip() is None and len(z.namelist())==len(set(z.namelist())),'bad official outer ZIP')
        for k,v in a['members'].items():need(fact(z.read(k))==v,'wrong C2 member '+k)
        native=json.loads(z.read('NATIVE-ACCEPTANCE.json'));src=json.loads(z.read('SOURCE.json'));graph=json.loads(z.read('NORMAL-GRAPH.json'))
        need(native['status']=='PASS_EXACT_CANONICAL_C2_NATIVE_ART_AND_ALL_DEVICE_SAVES' and src['head']==graph['base']==B and graph['status']=='PASS_EXACT_C2_CANONICAL_NO_DEPLOY','prior C2 native/source proof not qualified')
        for dev in ['PC','M']:need(all(x['checkpoint']=='complete' for lane in native['cases'][dev].values() for x in lane.values()),'prior C2 browser receipt incomplete')
        inner=z.read('C2-COMPILED-QA-ONLY.zip')
        need(fact(inner)==graph['normalQaZip'],'unbound normal C2 archive')
    c=w/'C';nxt=set(graph['aliases'].values());scope=nxt|SHELLS|{M}
    need(scope==set(graph['generated']) and len(scope)==11 and all(re.fullmatch(r'web/(runtime|entries|data)/[a-z0-9.-]+',k) for k in nxt),'bad compiled C2 scope')
    with zipfile.ZipFile(io.BytesIO(inner)) as z:
        need(len(z.namelist())==len(scope)==len(set(z.namelist())) and set(z.namelist())==scope and z.testzip() is None,'wrong exact C2 extracted paths')
        for k in scope:
            bb=z.read(k);need({**fact(bb),'git':blob(bb)}==graph['generated'][k],'wrong approved compiled byte '+k)
            dest=c/k;need(dest.resolve()==dest and dest.is_file()==(k not in nxt),'wrong stock predecessor before C2 overlay '+k);dest.write_bytes(bb)
    m=json.loads(read(c,M));rows=idx(m)
    need(len(rows)==P['base']['activeFiles'] and all(fact(read(c,k))==v for k,v in rows.items()),'reconstructed C2 normal active closure differs')
    proj=json.loads(read(c,m['project']))
    need(proj['stageLibraries'][39]==P['newPacket']['path'] and proj['stages'][39]==P['stage40']['map'],'wrong C2 map/packet')
    dump(w/'out'/'OFFICIAL-C2-ARM.json',{'status':'QA_ONLY_ARCHIVED_NORMAL_C2_NOT_PUBLICATION','prior':a,'activeFiles':len(rows),'currentBody':P['candidateSig']})
def graph(w):
    a,b=w/'B',w/'F';am,bm=[json.loads(read(x,M))for x in [a,b]];aa,ba=map(idx,[am,bm])
    for q,rows in [(a,aa),(b,ba)]:
        for k,v in rows.items():need(fact(read(q,k))==v,'physical active mismatch '+k)
    need(len(aa)==len(ba)==P['base']['activeFiles'],'wrong active count')
    cp=am['project'];need(cp==bm['project'] and read(a,cp)==read(b,cp),'fallback must preserve exact existing campaign')
    ac=json.loads(read(a,cp));pa=P['stage40']['packet'];s42=P['protectedStage42']
    need(ac['stageLibraries'][39]==pa and blob(read(b,pa))==P['stage40']['packetGit'] and ac['stages'][39]==P['stage40']['map'] and blob(read(b,ac['stages'][39]))==P['stage40']['mapGit'],'fallback not pre-C2 authority')
    need(ac['stageLibraries'][41]==s42['provider'] and ac['stages'][41]==s42['map'] and aa[s42['provider']]['sha256']==s42['providerSHA256'],'missing published Stage42 authority')
    need(len(ac['stages'])==len(ac['stageLibraries'])==50 and all(aa[k]==ba[k] for k in ac['stages']+ac['stageLibraries']),'protected 50 maps or 50 providers differ')
    def pick(m,p):
        f=[x for x in m['common'] if x.startswith(p)];need(len(f)==1,'wrong role '+p);return f[0]
    ck=P['stage40']['common12']
    def embed(m):
        v=m['playtest'];need(v.endswith('?embedded=1'),'wrong embedded Playtest');return v.removesuffix('?embedded=1')
    roles=[(ck,pick(bm,'web/runtime/ordered-common-12.')),(am['gameEntry'],bm['gameEntry']),(embed(am),embed(bm)),(am['workshopEntry'],bm['workshopEntry'])]
    pairs=dict(roles);need(len(pairs)==4 and all(x!=y for x,y in roles) and aa.keys()-ba.keys()==pairs.keys() and ba.keys()-aa.keys()==set(pairs.values()) and all(aa[k]==ba[k] for k in aa.keys()&ba.keys()),'extra active graph difference')
    def norm(s):
        for x,y in roles:s=s.replace(x,y).replace(Path(x).name,Path(y).name)
        return s
    def convert(o):
        if isinstance(o,str):return norm(o)
        if isinstance(o,list):return [convert(x) for x in o]
        if isinstance(o,dict):return {k:convert(v) for k,v in o.items()}
        return o
    need(convert({k:v for k,v in am.items() if k not in KEEP|{'files'}})=={k:v for k,v in bm.items() if k not in KEEP|{'files'}},'unrelated bootstrap changed')
    need(blob(read(a,ck))==P['stage40']['common12Git'],'wrong fallback source registry')
    row='"approved40:body":{stage:40,previous:"4724416:12a0c1d5",previousOptimized:["4471109:d3f5a835"],current:"1644042:df21ebc3"}'
    new=row.replace('["4471109:d3f5a835"]','["4471109:d3f5a835","1647277:af3b90a3"]')
    js=read(a,ck).decode();need(js.count(row)==1 and js.replace(row,new).encode()==read(b,pairs[ck]),'compiled fallback registry differs beyond exact C2 token')
    for x,y in roles[1:]:need(norm(read(a,x).decode()).encode()==read(b,y),'non-reference bootstrap change '+x)
    for k in SHELLS:need(norm(read(a,k).decode()).encode()==read(b,k),'non-reference shell change '+k)
    for k,v in P['source'].items():need(blob(read(b,k))==v['after'],'verified fallback source mutated')
    for k,v in P['sourceAuthority'].items():need(blob(read(b,k))==v,'protected source mutated since latest public')
    dump(w/'out'/'NORMAL-GRAPH.json',{'status':'PASS_EXACT_FORWARD_FALLBACK_NO_DEPLOY','base':B,'aliases':pairs,'scope':'all 50 maps and packets exact; only signed Stage40 guard row and four reference aliases','registry':new,'active':len(ba),'stage42Preserved':s42})
