"""Rebuild complete, nonoverlapping Unicode WOFF2 subsets from the pinned Noto source.
Usage: PYTHONPATH=<brotli directory> python3 tools/fonts/subset-korean.py SOURCE.ttf
Requires fonttools and brotli. Never drops a source cmap character.
"""
from pathlib import Path
import sys,json,hashlib
from fontTools import subset
from fontTools.ttLib import TTFont
font_path=Path(sys.argv[1]);out=Path('shared/assets/fonts/noto-serif-kr');out.mkdir(parents=True,exist_ok=True)
codepoints=sorted(TTFont(font_path).getBestCmap())
# Separate Latin/Jamo/punctuation, Hangul and CJK. Common KS X 1001 Hangul plus 256-codepoint Unicode pages
# keep individual downloads modest and cover arbitrary workshop/user text too.
groups={}
for cp in codepoints:
 try:common=0xAC00<=cp<=0xD7A3 and len(chr(cp).encode('euc_kr'))==2
 except UnicodeEncodeError:common=False
 key='hangul-common' if common else f'kr-{cp//256:04x}'
 groups.setdefault(key,[]).append(cp)
for previous in out.glob('*.woff2'):previous.unlink()
css=['/* Noto Serif KR variable 200–900, SIL OFL 1.1. Generated by tools/fonts/subset-korean.py. */']
records=[]
for page,points in groups.items():
 f=TTFont(font_path);options=subset.Options();options.flavor='woff2';options.layout_features=['*'];options.name_IDs=['*'];options.name_legacy=True;options.name_languages=['*'];worker=subset.Subsetter(options);worker.populate(unicodes=points);worker.subset(f);f.flavor='woff2';name=f'{page}.woff2';f.save(out/name)
 ranges=[];start=prev=points[0]
 for cp in points[1:]+[None]:
  if cp is not None and cp==prev+1:prev=cp;continue
  ranges.append(f'U+{start:X}'+(f'-{prev:X}' if start!=prev else ''))
  start=prev=cp
 css.append('@font-face{font-family:"Honro Serif";font-style:normal;font-weight:200 900;font-display:swap;src:url("../../shared/assets/fonts/noto-serif-kr/'+name+'") format("woff2");unicode-range:'+','.join(ranges)+'}')
 records.append({'file':name,'codepoints':points,'bytes':(out/name).stat().st_size})
Path('game/src/fonts.css').write_text('\n'.join(css)+'\n'+'''/* Titles, prose and compact numbers have explicit roles; no synthetic weights. */
:root{--font-title:"Honro Serif",serif;--font-body:"Honro Serif",serif;--font-readout:system-ui,sans-serif}
:root,.honro,#app,.honro button,.honro input,.honro select{font-family:var(--font-body);font-synthesis:none}
.honro{font-weight:500}
.honro :is(h1,h2,h3,.new-title,.hero-name){font-family:var(--font-title)}
.honro :is(.dialog p,.menu-note,.skill-desc,.training-card-desc,.rest-location p,.journey-detail p){font-weight:500;font-size:max(13px,1em)}
.honro :is(.debug-badge,.context-interact .keycap,.map-node .stage-index,.atlas-progress span,.shot-readout,.hpmp label,kbd){font-family:var(--font-readout);font-variant-numeric:tabular-nums}
''')
(out/'coverage.json').write_text(json.dumps({'sourceSha256':hashlib.sha256(font_path.read_bytes()).hexdigest(),'glyphCoverage':len(codepoints),'weightRange':[200,900],'subsets':records},separators=(',',':'))+'\n')
print(len(records),'subsets,',len(codepoints),'codepoints,',sum(r['bytes'] for r in records),'bytes')
