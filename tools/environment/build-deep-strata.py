"""Deep strata for flat below-floor slabs (2026-11-24).

Source: the approved Act 5 camp deep geology (shared/assets/environment/act5/camp-deep-geology.json),
simplified with tools/act5/simplify-vector.py (tol 2.5, min-area 40, min-box 8) and rounded to whole
source units. Output: shared/runtime/deep-strata-data.js (fills + paths in source order, viewBox).
Colours are re-mapped per stage at runtime by luminance against the source background.

python3 tools/environment/build-deep-strata.py
"""
import json, re, subprocess, pathlib, tempfile
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT/'shared/assets/environment/act5/camp-deep-geology.json'
OUT = ROOT/'shared/runtime/deep-strata-data.js'
with tempfile.TemporaryDirectory() as tmp:
    simp = pathlib.Path(tmp)/'geo.json'
    subprocess.run(['python3', str(ROOT/'tools/act5/simplify-vector.py'), str(SRC), str(simp), '--tol', '2.5', '--min-area', '40', '--min-box', '8', '--relative', '--close-open'], check=True)
    a = json.loads(simp.read_text())
rows = []
def walk(n):
    d = n.get('d') or ''.join(n.get('dParts') or []) or n.get('sourcePath')
    if n.get('fill') and d:
        toks = re.findall(r'[A-Za-z]|-?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?', d)
        out = []
        for t in toks:
            if t.isalpha(): out.append(t)
            else:
                v = str(round(float(t)))
                out.append(v if (not out or out[-1].isalpha() or v.startswith('-')) else ' ' + v)
        d = ''.join(out)
        rows.append([n['fill'], d, n.get('fillRule', 'nonzero')])
    for c in n.get('children') or []: walk(c)
walk(a['vector']['root'])
data = {'source': 'camp-deep-geology.json', 'viewBox': a['vector']['viewBox'], 'background': '#3a3029', 'paths': rows}
OUT.write_text('(function(G){\'use strict\';\n// Generated by tools/environment/build-deep-strata.py. Do not edit.\nG.HONRO_DEEP_STRATA=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n})(globalThis);\n')
print(OUT, OUT.stat().st_size, len(rows))
