(function(G){'use strict';
// The v4 plan's phase3 long spear uses the existing native melee sector,
// damage, terrain occlusion, focus cost and action/review lifecycle.
const V=G.HonroAct23V4,P=G.HonroAct23V4Stage29,C=G.HONRO_CORE;
const ID='V4_HAN_THRUST',POWER=.08,WINDUP=.65,rad=x=>x*Math.PI/180;
const R=()=>G.HonroAct23V4Chapter29Reviewed;
const active=b=>R()?.active(b)===true;
const boss=b=>b.units.find(u=>u.id===P.bossId);
const memory=b=>R().memory(b).spear??={revision:1,attacks:0};
const equipped=(b,u)=>active(b)&&u?.id===P.bossId&&P.memory(b).phase===3;
function install(){if(C.SKILLS[ID])return;const old=C.SKILLS.S09;
 C.SKILLS[ID]={...C.SKILLS.S00,id:ID,name:'장창',desc:'',tag:'장창',enemyOnly:true,basic:false,
  radius:200,damage:Math.min(C.SKILLS.S00.damage,old.damage),cost:old.cost,terrain:0};
}
function heading(u,h){let a=(-Math.atan2((h.y-h.h*.5)-(u.y-u.h*.5),h.x-u.x)*180/Math.PI+360)%360;if(a>C.AIM_MAX)a-=360;return C.clamp(a,C.AIM_MIN,C.AIM_MAX);}
function geometry(u,angle){const skill=C.SKILLS[ID];return{angle:-rad(angle),range:C.meleeRange(u,skill,POWER),span:C.meleeSpan(u,skill,POWER)};}
function targets(e,angle){const b=e.b,u=boss(b);if(!V.alive(u)||!e.grounded(u))return[];
 const g=geometry(u,angle);return V.heroes(b).filter(h=>C.meleeContains(e,u,h,g.range,g.angle,g.span));
}
function holding(b){return active(b)&&['telegraph','windup'].includes(memory(b).plan?.status)&&V.alive(boss(b));}
function valid(e,p){const b=e.b,u=boss(b);return !!p&&V.alive(u)&&P.memory(b).phase===3&&e.grounded(u)&&
 Math.hypot(u.x-p.origin.x,u.y-p.origin.y)<5&&targets(e,p.angle).length>0;}
function cancel(b,reason){const s=memory(b),p=s.plan;if(!p||!['telegraph','windup'].includes(p.status))return;
 p.status='cancelled';p.reason=reason;const u=boss(b);if(u)delete u.honroReviewedSpearPose;
}
function observe(app){const e=app.engine,b=e.b;if(!active(b))return;install();const s=memory(b),u=boss(b);
 if(holding(b)&&!valid(e,s.plan))cancel(b,V.alive(u)?'lane-cleared':'boss-dead');
 if(s.plan?.status==='striking'&&!u.meleeAction){s.last=s.plan;delete s.plan;delete u.honroReviewedSpearPose;}
 if(b.side!==0||b.phase!=='aim'||!V.safe(app)||!V.alive(u)||P.memory(b).phase!==3||
  (P.memory(b).advanceDistance||0)<=5||holding(b)||s.plan?.status==='striking')return;
 // One declared physical intent per main-hero round. Withdrawal cancels it;
 // no repeated plan/voice queue is generated by idle render ticks.
 if(s.plannedRound===b.round)return;
 const threat=V.heroes(b).filter(h=>Math.hypot(h.x-u.x,h.y-u.y)<280).find(h=>{
  const a=heading(u,h);return targets(e,a).some(t=>t.id===h.id);
 });if(!threat)return;
 const angle=heading(u,threat);
 s.plannedRound=b.round;s.plan={status:'telegraph',angle,power:POWER,elapsed:0,round:b.round,
  origin:{x:u.x,y:u.y},targetIds:targets(e,angle).map(h=>h.id),serial:b.honroState.actorTurnSerial||0};
 u.facing=Math.cos(rad(angle))>=0?1:-1;u.honroReviewedSpearPose=true;
 app.dirty=true;e.emit?.('save');
}
function warning(app){const b=app.engine.b;return active(b)&&holding(b)&&valid(app.engine,memory(b).plan);}
function attach(app,e){if(e.honroReviewed29Spear)return;e.honroReviewed29Spear=true;install();
 const walk=e.walk.bind(e);e.walk=function(u,...args){return active(e.b)&&u?.id===P.bossId&&holding(e.b)?false:walk(u,...args);};
 const enemy=e.enemyAction.bind(e);e.enemyAction=function(...args){const b=e.b;if(!active(b)||!holding(b)||b.active!==P.bossId)return enemy(...args);
  const s=memory(b),p=s.plan,u=boss(b);if(!valid(e,p)){cancel(b,'lane-cleared');return enemy(...args);}
  if(u.acted||e.settleBusy()||b.projectiles.length||b.phase!=='enemy')return;
  p.status='windup';if(p.elapsed<WINDUP)return;
  const original=u.loadout;u.loadout=[...original,ID];let launched=false;
  try{launched=e.fire(ID,p.angle,POWER,true);}finally{u.loadout=original;}
  if(launched){p.status='striking';p.shot=b.shot;s.attacks++;s.lastLaunch={shot:b.shot,skill:ID,angle:p.angle,
   origin:{x:u.x,y:u.y-u.h*.5},geometry:geometry(u,p.angle),targets:targets(e,p.angle).map(h=>h.id)};app.dirty=true;}
  else {cancel(b,'native-cast-rejected');return enemy(...args);}
 };
 const tick=e.tick.bind(e);e.tick=function(dt,...args){const b=e.b;if(!active(b))return tick(dt,...args);
  if(holding(b)&&(app.dialogue||app.modal?.classList.contains('open')||app.done||G.document?.hidden))return;
  observe(app);const p=memory(b).plan;
  if(holding(b)&&b.phase==='enemy'&&b.side===1&&b.active===P.bossId&&!boss(b).acted)
   p.elapsed=Math.min(WINDUP,p.elapsed+Math.max(0,Math.min(dt,.05)));
  const out=tick(dt,...args);if(!V.alive(boss(b)))cancel(b,'boss-dead');return out;
 };
 const hurt=e.hurt.bind(e);e.hurt=function(u,...args){const out=hurt(u,...args);if(u?.id===P.bossId&&!V.alive(u)&&active(e.b))cancel(e.b,'boss-dead');return out;};
}
function draw(scene,c,b){const u=boss(b);if(!equipped(b,u)||!V.alive(u))return;install();const p=memory(b).plan,a=u.meleeAction;
 const angle=p&&['telegraph','windup','striking'].includes(p.status)?p.angle:(u.facing<0?150:30),g=geometry(u,angle),x=u.x,y=u.y-u.h*.5;
 c.save();c.translate(x,y);c.rotate(g.angle);
 if(holding(b)){c.fillStyle='#d6ac6d22';c.strokeStyle='#d6ac6d99';c.lineWidth=2;c.setLineDash([7,6]);c.beginPath();c.moveTo(0,0);c.arc(0,0,g.range,-g.span/2,g.span/2);c.closePath();c.fill();c.stroke();c.setLineDash([]);}
 const tip=a?.skill===ID?g.range*(.65+.35*Math.min(1,a.elapsed/.075)):g.range*.65;
 c.strokeStyle='#6f5f42';c.lineWidth=6;c.lineCap='round';c.beginPath();c.moveTo(-65,0);c.lineTo(tip-22,0);c.stroke();
 c.fillStyle='#b6b8a7';c.strokeStyle='#3a4947';c.lineWidth=1.5;c.beginPath();c.moveTo(tip,0);c.lineTo(tip-25,-7);c.lineTo(tip-19,0);c.lineTo(tip-25,7);c.closePath();c.fill();c.stroke();c.restore();
}
// Install before ProfileStore validates an unfinished native cast on reload.
// Chapter flags are emitted before model modules; flag-off builds keep skills intact.
if(G.HONRO_ACT23_V4_PHASE_A===true&&G.HONRO_ACT23_V4_PHASE_B_CH29===true)install();
G.HonroAct23V4Chapter29Spear={ID,POWER,WINDUP,active,equipped,memory,targets,geometry,holding,warning,observe,attach,draw};
})(globalThis);
