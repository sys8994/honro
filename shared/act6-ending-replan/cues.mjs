export const selectEndingCue=(cuts,ms)=>{
 const sec=Math.max(ms,0)/1000;
 let start=0;
 for(const [index,cut] of cuts.entries()){
  const time=sec-start;
  if(time<cut.duration){
   const final=cut.id==='final',num=cut.beats.length,ends=cut.beatEnds??cut.beats.map((_,i)=>(i+1)*cut.duration/num);
   const beat=ends.findIndex(end=>time<end);
   const beatStart=beat===0?0:ends[beat-1],beatSpan=ends[beat]-beatStart;
   return {index,beat,time,start,beatStart,beatSpan,cut,final};
  }
  start+=cut.duration;
 }
 return null;
};
export const cueAt=ms=>selectEndingCue(cuts,ms);
